CREATE TABLE rota (
    id UUID PRIMARY KEY,
    nome TEXT NOT NULL
);

CREATE TABLE parada (
    id UUID PRIMARY KEY,
    rota_id UUID NOT NULL REFERENCES rota(id),
    nome TEXT NOT NULL,
    km_desde_origem DOUBLE PRECISION NOT NULL,
    minutos_desde_origem INTEGER NOT NULL,
    ordem INTEGER NOT NULL,
    CONSTRAINT uq_parada_rota_ordem UNIQUE (rota_id, ordem),
    CONSTRAINT ck_parada_km CHECK (km_desde_origem >= 0),
    CONSTRAINT ck_parada_minutos CHECK (minutos_desde_origem >= 0),
    CONSTRAINT ck_parada_ordem CHECK (ordem > 0)
);

CREATE TABLE viagem (
    id UUID PRIMARY KEY,
    rota_id UUID NOT NULL REFERENCES rota(id),
    data_hora_partida TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL,
    sequencia BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    CONSTRAINT ck_viagem_status CHECK (status IN ('AGENDADA', 'EM_ANDAMENTO', 'ENCERRADA'))
);
CREATE INDEX ix_viagem_rota ON viagem(rota_id);

